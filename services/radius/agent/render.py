def _event_json(kind: str, result: str = "") -> str:
    """One JSON object per line. Attribute values are escaped by rlm_json's %{json_encode:}; the wrapper fields are
    digits or hex only."""
    if kind == "auth":
        return '{\\"uid\\":\\"' + UID + '\\",\\"ts\\":%l.%M,\\"result\\":\\"' + result + '\\",\\"rec\\":%{json_encode:' + AUTH_ATTRS + '}}'
    return '{\\"ts\\":%l,\\"rec\\":%{json_encode:' + ACCT_ATTRS + '}}'


