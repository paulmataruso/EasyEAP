"""Render a complete FreeRADIUS 3.2 configuration from EasyEAP's desired state.

Layout of a rendered tree (one per version, swapped atomically):
  radiusd.conf, dictionary, clients.conf
  mods-enabled/   eap_<t> (one EAP-TLS instance per tenant), authz (SQLite), linelog_auth, linelog_acct, json, expr, always
  sites-enabled/  easyeap_listen (shared 1812/1813), t_<t> (tenant), t_<t>_check (certificate authorization)
  tenants/<t>/    server.pem, server.key (0600), ca.pem (issuing + root + CRLs)
"""
from __future__ import annotations

import os
import re
import stat
from pathlib import Path

SAFE = re.compile(r"^[A-Za-z0-9._ -]*$")
ALLOWED_EXTRA = ("Session-Timeout", "Filter-Id", "Reply-Message", "Class", "Termination-Action", "Airespace-ACL-Name", "Aruba-User-Role", "Cisco-AVPair")


def short(tenant_id: str) -> str:
    return tenant_id.replace("-", "")[:12]


def q(value: str) -> str:
    """Quote a value for a FreeRADIUS config string. Rejects characters that could break out of the string."""
    if any(c in value for c in '"\\\n\r'):
        raise ValueError("unsafe character in configuration value")
    return f'"{value}"'


def _write(path: Path, content: str, private: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    fd = os.open(path, flags, stat.S_IRUSR | stat.S_IWUSR if private else 0o644)
    with os.fdopen(fd, "w") as f:
        f.write(content)


