def render(desired: dict, raddb: Path, state: str) -> None:
    raddb.mkdir(parents=True, exist_ok=True)
    tenants = desired.get("tenants", [])
    _write(raddb / "radiusd.conf", RADIUSD.format(raddb=str(raddb), state=state))
    _write(raddb / "dictionary", DICTIONARY)
    _write(raddb / "clients.conf", clients_conf(tenants), private=True)
    for name, body in mods_common(state).items():
        _write(raddb / "mods-enabled" / name, body)
    _write(raddb / "sites-enabled" / "easyeap_listen", LISTEN_SITE)
    for t in tenants:
        s = short(t["id"])
        tdir = raddb / "tenants" / s
        _write(tdir / "server.pem", t["server_cert_pem"].strip() + "\n" + t["ca_pem"].split("-----END CERTIFICATE-----")[0] + "-----END CERTIFICATE-----\n")
        _write(tdir / "server.key", t["server_key_pem"], private=True)
        _write(tdir / "ca.pem", t["ca_pem"].strip() + "\n" + t["crl_pem"].strip() + "\n")
        _write(raddb / "mods-enabled" / f"eap_{s}", eap_module(t, str(raddb)))
        _write(raddb / "mods-enabled" / f"eapmd5_{s}", eapmd5_module(t))
        main, check = tenant_sites(t)
        _write(raddb / "sites-enabled" / f"t_{s}", main)
        _write(raddb / "sites-enabled" / f"t_{s}_check", check)
