"""Tenant PKI lifecycle on OpenBao: ceremony, templates → roles, issuance, revocation, CRL.

EasyEAP acts as the registration authority: subjects and SANs are always built from directory data and the
template's patterns. Requested subjects inside CSRs are ignored (`use_csr_common_name=false`,
`use_csr_sans=false`), so an enrolling device cannot obtain a certificate for anyone else.
"""
from __future__ import annotations

import secrets
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta

from sqlalchemy import select
from sqlalchemy.orm import Session

from app import models as m
from app.config import get_settings
from app.pki import crypto
from app.pki.openbao import OpenBao

KEY_PARAMS = {
    "ecdsa-p256": ("ec", 256),
    "ecdsa-p384": ("ec", 384),
    "rsa-2048": ("rsa", 2048),
    "rsa-3072": ("rsa", 3072),
    "rsa-4096": ("rsa", 4096),
}
EKU_MAP = {"clientAuth": "ClientAuth", "serverAuth": "ServerAuth"}
UPN_OID = "1.3.6.1.4.1.311.20.2.3"


class PkiError(ValueError):
    pass


def tenant_mount(tenant_id: uuid.UUID) -> str:
    return f"pki-t-{tenant_id}"


def pki_urls(tenant_id: uuid.UUID) -> dict[str, str]:
    base = get_settings().pki_public_url.rstrip("/")
    return {
        "ca": f"{base}/pki/{tenant_id}/ca.crt",
        "crl": f"{base}/pki/{tenant_id}/crl",
        "ocsp": f"{base}/pki/{tenant_id}/ocsp",
        "root_ca": f"{base}/pki/{tenant_id}/root.crt",
        "root_crl": f"{base}/pki/{tenant_id}/root.crl",
    }


@dataclass
class CeremonyRequest:
    organization: str
    country: str
    state: str
    locality: str
    root_common_name: str
    issuing_common_name: str
    key_algorithm: str = "ecdsa-p384"
    root_validity_years: int = 20
    issuing_validity_years: int = 8
    root_passphrase: str | None = None  # protects the exported root key
    keep_root_online: bool = False  # lab mode only


@dataclass
class CeremonyResult:
    root: m.CertificateAuthority
    issuing: m.CertificateAuthority
    encrypted_root_key_pem: bytes | None


def _subject_params(req: CeremonyRequest) -> dict:
    p = {"organization": req.organization}
    if req.country:
        p["country"] = req.country.upper()[:2]
    if req.state:
        p["province"] = req.state
    if req.locality:
        p["locality"] = req.locality
    return p


def run_ceremony(session: Session, bao: OpenBao, tenant: m.Tenant, req: CeremonyRequest) -> CeremonyResult:
    """Create the tenant's offline Root CA and online Issuing CA.

    The root key is generated by OpenBao in a temporary mount (type=exported), used to sign the issuing CA and the
    root CRL, returned once encrypted under the administrator's passphrase, and destroyed by unmounting.
    """
    if req.key_algorithm not in KEY_PARAMS:
        raise PkiError("Unsupported key algorithm.")
    if not req.keep_root_online and (not req.root_passphrase or len(req.root_passphrase) < 12):
        raise PkiError("Choose a passphrase of at least 12 characters to protect the offline root key.")
    if req.keep_root_online and not get_settings().lab_mode:
        raise PkiError("Keeping the root CA online is only available in lab mode.")
    existing = session.scalars(select(m.CertificateAuthority).where(m.CertificateAuthority.tenant_id == tenant.id, m.CertificateAuthority.status == "active")).first()
    if existing:
        raise PkiError("This tenant already has a certificate authority.")

    key_type, key_bits = KEY_PARAMS[req.key_algorithm]
    mount = tenant_mount(tenant.id)
    tmp = f"pki-root-{tenant.id}-{secrets.token_hex(4)}"
    urls = pki_urls(tenant.id)
    root_hours = req.root_validity_years * 8760
    iss_hours = min(req.issuing_validity_years * 8760, root_hours - 24)
    subject = _subject_params(req)

    bao.write(f"sys/mounts/{mount}", {"type": "pki", "description": f"EasyEAP issuing CA — {tenant.name}", "config": {"max_lease_ttl": f"{iss_hours}h"}})
    bao.write(f"sys/mounts/{tmp}", {"type": "pki", "description": "EasyEAP root ceremony (temporary)", "config": {"max_lease_ttl": f"{root_hours}h"}})
    try:
        root = bao.write(f"{tmp}/root/generate/exported", {
            "common_name": req.root_common_name, "key_type": key_type, "key_bits": key_bits, "ttl": f"{root_hours}h",
            "issuer_name": "root", "max_path_length": 1, "exclude_cn_from_sans": True, **subject,
        })["data"]
        root_pem, root_key_pem = root["certificate"], root["private_key"]
        bao.write(f"{tmp}/config/urls", {"issuing_certificates": [urls["root_ca"]], "crl_distribution_points": [urls["root_crl"]]})
        csr = bao.write(f"{mount}/intermediate/generate/internal", {
            "common_name": req.issuing_common_name, "key_type": key_type, "key_bits": key_bits, "exclude_cn_from_sans": True, **subject,
        })["data"]["csr"]
        signed = bao.write(f"{tmp}/root/sign-intermediate", {
            "csr": csr, "common_name": req.issuing_common_name, "ttl": f"{iss_hours}h", "max_path_length": 0,
            "exclude_cn_from_sans": True, "use_csr_values": False, "format": "pem", **subject,
        })["data"]["certificate"]
        bao.write(f"{mount}/intermediate/set-signed", {"certificate": f"{signed}\n{root_pem}"})
        bao.write(f"{mount}/config/urls", {"issuing_certificates": [urls["ca"]], "crl_distribution_points": [urls["crl"]], "ocsp_servers": [urls["ocsp"]]})
        bao.write(f"{mount}/config/crl", {"expiry": "72h", "auto_rebuild": False, "ocsp_disable": False})
        # Root CRL valid one year; re-issued during a root ceremony before it lapses (reminder job).
        bao.write(f"{tmp}/config/crl", {"expiry": "8760h"})
        bao.read(f"{tmp}/crl/rotate")
        root_crl = bao.get_text(f"{tmp}/crl/pem")
        encrypted_key = None if req.keep_root_online else crypto.encrypt_private_key_pem(root_key_pem, req.root_passphrase or "")
        del root_key_pem
    finally:
        if not req.keep_root_online:
            bao.delete(f"sys/mounts/{tmp}")  # destroys the online copy of the root key

    root_info, iss_info = crypto.cert_info(root_pem), crypto.cert_info(signed)
    root_ca = m.CertificateAuthority(
        tenant_id=tenant.id, role="root", common_name=root_info.common_name, subject=root_info.subject,
        key_algorithm=root_info.key_algorithm, serial=root_info.serial, fingerprint_sha256=root_info.fingerprint_sha256,
        not_before=root_info.not_before, not_after=root_info.not_after, certificate_pem=root_pem,
        offline=not req.keep_root_online, mount=tmp if req.keep_root_online else None, crl_pem=root_crl,
        crl_next_update=datetime.now(UTC) + timedelta(days=365),
    )
    issuing_ca = m.CertificateAuthority(
        tenant_id=tenant.id, role="issuing", common_name=iss_info.common_name, subject=iss_info.subject,
        key_algorithm=iss_info.key_algorithm, serial=iss_info.serial, fingerprint_sha256=iss_info.fingerprint_sha256,
        not_before=iss_info.not_before, not_after=iss_info.not_after, certificate_pem=signed, offline=False, mount=mount,
    )
    session.add_all([root_ca, issuing_ca])
    session.flush()
    from app.pki import renewal
    percent = renewal.settings(session, tenant.id).renew_at_percent
    for tpl in default_templates(tenant):
        tpl.renew_before_days = renewal.derived_days(tpl.validity_days, percent)
        session.add(tpl)
        write_role(bao, tenant.id, tpl, organization=req.organization)
    session.flush()
    return CeremonyResult(root=root_ca, issuing=issuing_ca, encrypted_root_key_pem=encrypted_key)


def default_templates(tenant: m.Tenant) -> list[m.CertificateTemplate]:
    return [
        m.CertificateTemplate(tenant_id=tenant.id, name="User Wi-Fi", purpose="user", key_algorithm="ecdsa-p256", validity_days=365,
                              renew_before_days=73, extended_key_usage=["clientAuth"], key_usage=["digitalSignature"],
                              subject_pattern="CN={upn}", san_patterns=["upn:{upn}", "email:{email}"],
                              allow_client_keygen=True, allow_server_keygen=True, bao_role="user-wifi"),
        m.CertificateTemplate(tenant_id=tenant.id, name="Device Wi-Fi", purpose="device", key_algorithm="ecdsa-p256", validity_days=730,
                              renew_before_days=146, extended_key_usage=["clientAuth"], key_usage=["digitalSignature"],
                              subject_pattern="CN={device}.{username}", san_patterns=["upn:{upn}"],
                              allow_client_keygen=True, allow_server_keygen=True, bao_role="device-wifi"),
        m.CertificateTemplate(tenant_id=tenant.id, name="RADIUS Server", purpose="radius-server", key_algorithm="ecdsa-p256", validity_days=397,
                              renew_before_days=80, extended_key_usage=["serverAuth"], key_usage=["digitalSignature"],
                              subject_pattern="CN={server}", san_patterns=["dns:{server}"],
                              allow_client_keygen=False, allow_server_keygen=True, bao_role="radius-server"),
    ]


def write_role(bao: OpenBao, tenant_id: uuid.UUID, tpl: m.CertificateTemplate, organization: str = "") -> None:
    key_type, key_bits = KEY_PARAMS.get(tpl.key_algorithm, ("ec", 256))
    key_usage = ["DigitalSignature"] + (["KeyEncipherment"] if key_type == "rsa" else [])
    is_server = "serverAuth" in tpl.extended_key_usage
    bao.write(f"{tenant_mount(tenant_id)}/roles/{tpl.bao_role}", {
        "allow_any_name": True, "enforce_hostnames": is_server, "allow_ip_sans": False, "allow_wildcard_certificates": False,
        "allowed_other_sans": [f"{UPN_OID};UTF8:*"], "allowed_uri_sans": [],
        "server_flag": is_server, "client_flag": "clientAuth" in tpl.extended_key_usage,
        "ext_key_usage": [EKU_MAP[e] for e in tpl.extended_key_usage if e in EKU_MAP], "key_usage": key_usage,
        "key_type": "any" if tpl.allow_client_keygen else key_type, "key_bits": 0 if tpl.allow_client_keygen else key_bits,
        "signature_bits": 0, "ttl": f"{tpl.validity_days * 24}h", "max_ttl": f"{tpl.validity_days * 24}h",
        "use_csr_common_name": False, "use_csr_sans": False, "require_cn": True, "no_store": False,
        "organization": [organization] if organization else [], "not_before_duration": "60s",
        "basic_constraints_valid_for_non_ca": False,
    })


def render_names(tpl: m.CertificateTemplate, values: dict[str, str]) -> tuple[str, list[str], list[str]]:
    """Return (common_name, alt_names, other_sans) from template patterns and directory values."""
    def fill(pattern: str) -> str:
        out = pattern
        for k, v in values.items():
            out = out.replace("{" + k + "}", v or "")
        if "{" in out:
            raise PkiError(f"Template field missing for pattern {pattern!r}.")
        return out

    cn_pattern = tpl.subject_pattern.split("CN=", 1)[-1].split(",", 1)[0]
    cn = fill(cn_pattern)
    alt, other = [], []
    for p in tpl.san_patterns:
        kind, _, pat = p.partition(":")
        try:
            val = fill(pat)
        except PkiError:
            continue  # optional SAN without data (e.g. no email) is skipped
        if not val:
            continue
        if kind == "upn":
            other.append(f"{UPN_OID};UTF8:{val}")
        elif kind in ("email", "dns"):
            alt.append(val)
    if not cn:
        raise PkiError("The certificate subject would be empty.")
    return cn, alt, other


def names_for_identity(identity: m.Identity, device_name: str, tenant: m.Tenant) -> dict[str, str]:
    safe_device = "".join(c if c.isalnum() or c == "-" else "-" for c in device_name.lower()).strip("-")[:40] or "device"
    return {
        "upn": identity.upn or f"{identity.username}@{tenant.domain}",
        "username": identity.username,
        "email": identity.email or "",
        "display_name": identity.display_name,
        "device": safe_device,
        "domain": tenant.domain,
        "tenant": tenant.slug,
    }


def issuing_ca(session: Session, tenant_id: uuid.UUID) -> m.CertificateAuthority:
    ca = session.scalars(select(m.CertificateAuthority).where(
        m.CertificateAuthority.tenant_id == tenant_id, m.CertificateAuthority.role == "issuing", m.CertificateAuthority.status == "active")).first()
    if not ca:
        raise PkiError("Initialize this tenant's PKI before issuing certificates.")
    return ca


def capped_ttl_hours(ca: m.CertificateAuthority, validity_days: int, now: datetime | None = None) -> int:
    """A leaf's lifetime in hours: the template's validity, or less when the issuing CA expires sooner (OpenBao refuses a
    leaf that outlives its CA). Under a day left: refused, with a reason an admin can act on."""
    now = now or datetime.now(UTC)
    left = int((ca.not_after - now).total_seconds() // 3600) - 1
    if left < 24:
        raise PkiError(f"The issuing CA expires on {ca.not_after:%Y-%m-%d %H:%M} UTC, too soon to issue certificates. Renew the issuing CA.")
    return min(validity_days * 24, left)


def root_ca(session: Session, tenant_id: uuid.UUID) -> m.CertificateAuthority | None:
    return session.scalars(select(m.CertificateAuthority).where(
        m.CertificateAuthority.tenant_id == tenant_id, m.CertificateAuthority.role == "root", m.CertificateAuthority.status == "active")).first()


def _record(session: Session, tenant_id: uuid.UUID, ca: m.CertificateAuthority, tpl: m.CertificateTemplate, pem: str,
            key_origin: str, identity_id: uuid.UUID | None, device_id: uuid.UUID | None, enrollment_id: uuid.UUID | None) -> m.Certificate:
    info = crypto.cert_info(pem)
    cert = m.Certificate(
        tenant_id=tenant_id, serial=info.serial, issuer_ca_id=ca.id, template_id=tpl.id, identity_id=identity_id, device_id=device_id,
        purpose=tpl.purpose, subject=info.subject, common_name=info.common_name, sans=info.sans, not_before=info.not_before,
        not_after=info.not_after, key_algorithm=info.key_algorithm, key_origin=key_origin, fingerprint_sha256=info.fingerprint_sha256,
        certificate_pem=pem, status="active", enrollment_id=enrollment_id,
    )
    session.add(cert)
    session.flush()
    return cert


def sign_csr(session: Session, bao: OpenBao, tenant: m.Tenant, tpl: m.CertificateTemplate, csr_pem: str, names: dict[str, str], *,
             key_origin: str, identity_id: uuid.UUID | None, device_id: uuid.UUID | None, enrollment_id: uuid.UUID | None = None) -> m.Certificate:
    if not tpl.allow_client_keygen:
        raise PkiError("This template does not accept certificate requests.")
    crypto.csr_info(csr_pem)  # validates signature and key type
    ca = issuing_ca(session, tenant.id)
    cn, alt, other = render_names(tpl, names)
    data = bao.write(f"{tenant_mount(tenant.id)}/sign/{tpl.bao_role}", {
        "csr": csr_pem, "common_name": cn, "alt_names": ",".join(alt), "other_sans": ",".join(other),
        "ttl": f"{capped_ttl_hours(ca, tpl.validity_days)}h", "format": "pem", "exclude_cn_from_sans": True,
    })["data"]
    return _record(session, tenant.id, ca, tpl, data["certificate"], key_origin, identity_id, device_id, enrollment_id)


# ── Group Policy autoenrollment: OpenBao CEL roles (docs/plans/gpo-autoenrollment.md §2.5) ──────────────────────

def _autoenroll_program(max_hours: int) -> dict:
    """The role's CEL program. It fixes what EasyEAP mustn't vary (not a CA, digital signature, client authentication,
    validity capped) and takes from the request only the subject CN and two extensions, by OID: the certificate
    template extension Windows needs and the subject alternative name EasyEAP built from the directory."""
    return {"cel_program": {
        "variables": [
            {"name": "ok", "expression": "has(request.cn) && has(request.template_ext) && has(request.san) && has(request.ttl) && "
                                         f"duration(request.ttl) > duration('1h') && duration(request.ttl) <= duration('{max_hours}h')"},
            {"name": "cert", "expression":
                "CertTemplate{Subject: PKIX.Name{CommonName: request.cn}, NotBefore: now - duration('5m'), "
                "NotAfter: now + duration(request.ttl), KeyUsage: KeyUsage.KeyUsageDigitalSignature, "
                "ExtKeyUsage: [ExtKeyUsage.ExtKeyUsageClientAuth], BasicConstraintsValid: true, IsCA: false, ExtraExtensions: ["
                "PKIX.Extension{Id: [1, 3, 6, 1, 4, 1, 311, 21, 7], Critical: false, Value: base64.decode(request.template_ext)}, "
                "PKIX.Extension{Id: [2, 5, 29, 17], Critical: false, Value: base64.decode(request.san)}]}"},
            {"name": "output", "expression": "ValidationOutput{template: cert, issuer_ref: 'default'}"},
        ],
        "expression": "ok ? output : 'EasyEAP autoenrollment: missing or out-of-range request fields'",
    }}


def write_autoenroll_role(bao: OpenBao, tenant_id: uuid.UUID, tpl: m.CertificateTemplate) -> None:
    bao.write(f"{tenant_mount(tenant_id)}/cel/roles/{tpl.bao_role}", _autoenroll_program(tpl.validity_days * 24))


def sign_autoenroll(session: Session, bao: OpenBao, tenant: m.Tenant, tpl: m.CertificateTemplate, csr_pem: str, *, common_name: str,
                    san_der: bytes, template_ext_der: bytes, ttl: timedelta, identity_id: uuid.UUID, device_id: uuid.UUID | None) -> m.Certificate:
    """Issue through the template's CEL role. The CSR's own subject and extensions are ignored."""
    import base64

    ca = issuing_ca(session, tenant.id)
    data = bao.write(f"{tenant_mount(tenant.id)}/cel/sign/{tpl.bao_role}", {
        "csr": csr_pem, "cn": common_name, "san": base64.b64encode(san_der).decode(),
        "template_ext": base64.b64encode(template_ext_der).decode(), "ttl": f"{int(ttl.total_seconds())}s",
    })["data"]
    return _record(session, tenant.id, ca, tpl, data["certificate"], "device", identity_id, device_id, None)


def issue_with_server_key(session: Session, bao: OpenBao, tenant: m.Tenant, tpl: m.CertificateTemplate, names: dict[str, str], *,
                          identity_id: uuid.UUID | None, device_id: uuid.UUID | None, enrollment_id: uuid.UUID | None = None) -> tuple[m.Certificate, str]:
    """Issue with a key generated inside OpenBao. The caller must protect the returned key immediately."""
    if not tpl.allow_server_keygen:
        raise PkiError("This template does not allow server-generated keys.")
    ca = issuing_ca(session, tenant.id)
    cn, alt, other = render_names(tpl, names)
    key_type, key_bits = KEY_PARAMS.get(tpl.key_algorithm, ("ec", 256))
    data = bao.write(f"{tenant_mount(tenant.id)}/issue/{tpl.bao_role}", {
        "common_name": cn, "alt_names": ",".join(alt), "other_sans": ",".join(other), "ttl": f"{capped_ttl_hours(ca, tpl.validity_days)}h",
        "format": "pem", "private_key_format": "pkcs8", "exclude_cn_from_sans": True, "key_type": key_type, "key_bits": key_bits,
    })["data"]
    cert = _record(session, tenant.id, ca, tpl, data["certificate"], "server", identity_id, device_id, enrollment_id)
    return cert, data["private_key"]


def revoke(session: Session, bao: OpenBao, cert: m.Certificate, reason: str, actor: str) -> None:
    if cert.status == "revoked":
        return
    ca = session.get(m.CertificateAuthority, cert.issuer_ca_id)
    if not ca or not ca.mount:
        raise PkiError("Issuing CA not found.")
    bao.write(f"{ca.mount}/revoke", {"serial_number": crypto.bao_serial(cert.serial)})  # CRL rebuilds on revoke
    cert.status = "revoked"
    cert.revoked_at = datetime.now(UTC)
    cert.revocation_reason = reason
    cert.revoked_by = actor


def rotate_crl(bao: OpenBao, tenant_id: uuid.UUID, session: Session | None = None) -> None:
    """Rebuild the issuing CA's CRL. With a session, also record when it expires, for the posture queue."""
    bao.read(f"{tenant_mount(tenant_id)}/crl/rotate")
    if session is not None:
        record_crl(session, bao, tenant_id)


def record_crl(session: Session, bao: OpenBao, tenant_id: uuid.UUID) -> datetime | None:
    from cryptography import x509

    crl = x509.load_pem_x509_crl(crl_pem(bao, tenant_id).encode())
    issuing_ca(session, tenant_id).crl_next_update = crl.next_update_utc
    return crl.next_update_utc


def crl_pem(bao: OpenBao, tenant_id: uuid.UUID) -> str:
    return bao.get_text(f"{tenant_mount(tenant_id)}/crl/pem")


def crl_der(bao: OpenBao, tenant_id: uuid.UUID) -> bytes:
    return bao.get_bytes(f"{tenant_mount(tenant_id)}/crl")


def chain_pem(session: Session, tenant_id: uuid.UUID) -> tuple[str, str | None]:
    """(issuing CA PEM, root CA PEM)."""
    iss = issuing_ca(session, tenant_id)
    root = root_ca(session, tenant_id)
    return iss.certificate_pem.strip() + "\n", (root.certificate_pem.strip() + "\n") if root else None


def effective_status(cert: m.Certificate, warning_days: int, now: datetime | None = None) -> str:
    now = now or datetime.now(UTC)
    if cert.status == "revoked":
        return "revoked"
    if cert.not_after <= now:
        return "expired"
    # Renewed: a newer certificate replaced it. RADIUS still accepts it until it expires, but it needs no renewal.
    if cert.status == "superseded":
        return "superseded"
    if cert.not_after - now <= timedelta(days=warning_days):
        return "expiring"
    return "active"


def destroy_tenant_pki(bao: OpenBao, tenant_id: uuid.UUID) -> None:
    bao.delete(f"sys/mounts/{tenant_mount(tenant_id)}")
