import { now } from '@/prototype/store'
import { relativeTime } from '@/ui/lib'

/** Real time the page loaded. Used only to map timestamps created during this session onto the demo clock. */
const SESSION_START = Date.now()

/** Timestamp on the demo clock. Rows created by in-session actions carry wall-clock times; shift them. */
function demoTime(iso: string): number {
  const t = new Date(iso).getTime()
  if (t >= SESSION_START && t <= Date.now() + 1_000) return now().getTime() - Math.max(0, Date.now() - t)
  return t
}

/** "3 minutes ago" on the demo clock; never "in the future" for rows created this session. */
export function since(iso: string | null): string {
  if (!iso) return 'Never'
  const t = demoTime(iso)
  if (now().getTime() - t < 45_000) return 'just now'
  return relativeTime(new Date(t).toISOString(), now())
}

/** "in 12 days" / "3 days ago" relative to the demo clock. */
export const until = (iso: string | null) => relativeTime(iso, now())

/** Human duration since a timestamp: "3 hours", "26 hours", "4 minutes". */
export function ageOf(iso: string | null): string {
  if (!iso) return 'ever'
  const ms = now().getTime() - demoTime(iso)
  const minutes = Math.round(ms / 60_000)
  if (minutes < 60) return plural(Math.max(1, minutes), 'minute')
  const hours = Math.round(ms / 3_600_000)
  if (hours < 48) return plural(hours, 'hour')
  return plural(Math.round(ms / 86_400_000), 'day')
}

export const plural = (n: number, one: string, many = `${one}s`) => `${n.toLocaleString('en-US')} ${n === 1 ? one : many}`

export const count = (n: number) => n.toLocaleString('en-US')

export function list(items: string[]): string {
  if (items.length <= 1) return items.join('')
  if (items.length === 2) return `${items[0]} and ${items[1]}`
  return `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`
}

export const firstName = (displayName: string) => displayName.split(' ')[0]

export const possessive = (name: string) => (name.endsWith('s') ? `${name}’` : `${name}’s`)

