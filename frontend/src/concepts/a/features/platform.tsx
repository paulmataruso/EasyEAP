import { Laptop, Monitor, Smartphone, SquareTerminal, TabletSmartphone } from 'lucide-react'
import type { KeyOrigin, Platform } from '@/domain/types'

export const PLATFORM_ICON: Record<Platform, typeof Laptop> = {
  windows: Monitor,
  macos: Laptop,
  ios: Smartphone,
  android: TabletSmartphone,
  linux: SquareTerminal,
}

export const PLATFORM_NOUN: Record<Platform, string> = {
  windows: 'Laptop',
  macos: 'MacBook',
  ios: 'iPhone',
  android: 'Android phone',
  linux: 'Workstation',
}

export const keyOriginLabels: Record<KeyOrigin, string> = {
  device: 'Generated on the device',
  browser: 'Generated in the enrollment browser',
  csr: 'Submitted as a CSR',
  server: 'Generated by EasyEAP (admin mode)',
}

export function PlatformIcon({ platform, className }: { platform: Platform; className?: string }) {
  const Icon = PLATFORM_ICON[platform]
  return <Icon className={className ?? 'size-4'} aria-hidden />
}
